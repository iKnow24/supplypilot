/**
 * Security headers. The Content-Security-Policy is per request (it carries a fresh nonce, set
 * in src/proxy.ts); the rest are static (next.config.ts).
 *
 * Production CSP: scripts and styles only from our origin or carrying this request's nonce
 * ('strict-dynamic' lets Next's nonce'd bootstrap load its chunks). No third-party origins at
 * all: the browser never talks to Supabase or the optimizer directly.
 * Development adds what React's dev tooling needs ('unsafe-eval', inline styles, HMR socket).
 */
export function contentSecurityPolicy(nonce: string, dev: boolean): string {
  return [
    "default-src 'self'",
    `script-src 'self' 'nonce-${nonce}' 'strict-dynamic'${dev ? " 'unsafe-eval'" : ""}`,
    dev ? "style-src 'self' 'unsafe-inline'" : `style-src 'self' 'nonce-${nonce}'`,
    "img-src 'self' blob: data:",
    "font-src 'self'",
    `connect-src 'self'${dev ? " ws: wss:" : ""}`,
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    ...(dev ? [] : ["upgrade-insecure-requests"]),
  ].join("; ");
}

export function newNonce(): string {
  return btoa(crypto.randomUUID());
}

