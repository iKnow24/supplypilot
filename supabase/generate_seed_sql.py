#!/usr/bin/env python3
"""Generate supabase/seed.sql from data/seed/demo_catalog.json (stdlib only).

Seeds, for each fictional demo buyer in the catalog:
  * a buyer_orgs row,
  * one demo Supabase Auth user (email demo.<slug>@supplypilot.test) and its membership,
  * the buyer's saved lists, with the same ids the catalog and optimizer scenarios use.

The demo password is a LOCAL TEST VALUE for fictional users, not a secret. Never run this seed
against a hosted project that real people sign in to.

Run:  python3 supabase/generate_seed_sql.py     (CI checks the output is current)
"""

from __future__ import annotations

import json
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "data" / "seed" / "demo_catalog.json"
OUT = ROOT / "supabase" / "seed.sql"

# Keep in sync with apps/web/src/lib/auth/demo-users.ts (an integration test signs in with it).
DEMO_PASSWORD = "supplypilot-demo-only"
DEMO_EMAIL_DOMAIN = "supplypilot.test"
NAMESPACE = uuid.UUID("6f1c2b7e-3f0a-4a8e-9a51-2b1d5f0c9e11")


def q(value: str | None) -> str:
    if value is None:
        return "null"
    return "'" + value.replace("'", "''") + "'"


def demo_email(org_id: str) -> str:
    return f"demo.{org_id.removeprefix('org_')}@{DEMO_EMAIL_DOMAIN}"


def main() -> None:
    catalog = json.loads(CATALOG.read_text())
    out: list[str] = [
        "-- GENERATED by supabase/generate_seed_sql.py from data/seed/demo_catalog.json.",
        "-- Do not edit by hand. Fictional demo buyers only; local test password.",
        "",
    ]
    for buyer in catalog["buyers"]:
        org = buyer["id"]
        user_id = str(uuid.uuid5(NAMESPACE, org))
        email = demo_email(org)
        out += [
            f"-- {buyer['name']}",
            "insert into public.buyer_orgs (id, name, synthetic) values "
            f"({q(org)}, {q(buyer['name'])}, {str(buyer['synthetic']).lower()});",
            "insert into auth.users (instance_id, id, aud, role, email, encrypted_password,",
            "  email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at,",
            "  confirmation_token, email_change, email_change_token_new, recovery_token)",
            "values ('00000000-0000-0000-0000-000000000000', "
            f"{q(user_id)}, 'authenticated', 'authenticated', {q(email)},",
            f"  extensions.crypt({q(DEMO_PASSWORD)}, extensions.gen_salt('bf')), now(),",
            """  '{"provider":"email","providers":["email"]}', """
            f"""'{{"demo_org":"{org}"}}', now(), now(), '', '', '', '');""",
            "insert into auth.identities (id, user_id, provider_id, identity_data, provider,",
            "  last_sign_in_at, created_at, updated_at)",
            f"values ({q(user_id)}, {q(user_id)}, {q(user_id)},",
            f"""  '{{"sub":"{user_id}","email":"{email}","email_verified":true}}', 'email',""",
            "  now(), now(), now());",
            "insert into public.org_members (user_id, org_id, role) values "
            f"({q(user_id)}, {q(org)}, 'owner');",
        ]
        for lst in buyer["saved_lists"]:
            out.append(
                "insert into public.saved_lists (id, org_id, name) values "
                f"({q(lst['id'])}, {q(org)}, {q(lst['name'])});"
            )
            rows = [
                f"  ({q(lst['id'])}, {q(org)}, {q(line['product_id'])}, {line['quantity']}, "
                f"{q(line['unit'])}, {q(line['current_supplier_id'])}, {pos})"
                for pos, line in enumerate(lst["lines"])
            ]
            out.append(
                "insert into public.saved_list_lines "
                "(list_id, org_id, product_id, quantity, unit, current_supplier_id, position) values\n"
                + ",\n".join(rows)
                + ";"
            )
        out.append("")
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
