#!/usr/bin/env python3
"""Generate supabase/seed.sql from data/seed/demo_catalog.json (stdlib only).

Seeds, for each fictional demo buyer in the catalog:
  * a buyer_orgs row,
  * one demo Supabase Auth user (email demo.<slug>@supplypilot.test) and its membership,
  * the buyer's saved lists, with the same ids the catalog and optimizer scenarios use,
  * demo stock for the items on their weekly list: 8 weeks of usage and one shelf count (a buyer
    with no lists, like the brand-new bakery, starts empty),
  * the starting state "Reset demo" restores (public.demo_seed).

The demo password is a LOCAL TEST VALUE for fictional users, not a secret. Never run this seed
against a hosted project that real people sign in to.

Run:  python3 supabase/generate_seed_sql.py     (CI checks the output is current)
"""

from __future__ import annotations

import hashlib
import json
import uuid
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "data" / "seed" / "demo_catalog.json"
OUT = ROOT / "supabase" / "seed.sql"

# Keep in sync with apps/web/src/lib/auth/demo-users.ts (an integration test signs in with it).
DEMO_PASSWORD = "supplypilot-demo-only"
DEMO_EMAIL_DOMAIN = "supplypilot.test"
NAMESPACE = uuid.UUID("6f1c2b7e-3f0a-4a8e-9a51-2b1d5f0c9e11")


def q(value: str | None) -> str:
    if value is None:
        return "null"
    return "'" + value.replace("'", "''") + "'"


def demo_email(org_id: str) -> str:
    return f"demo.{org_id.removeprefix('org_')}@{DEMO_EMAIL_DOMAIN}"


# Stock levels relative to a week's use, cycled over each buyer's weekly list so the demo
# shows every state: short before delivery, needs ordering, and fine for now.
ON_HAND_WEEKS = [0.1, 0.5, 1.7, 0.8, 0.3, 2.2, 0.6, 1.1, 1.9, 0.45, 0.7, 0.25, 1.0, 0.55, 2.4, 0.9]
USAGE_WEEKS = 8


def unit_fraction(*parts: str) -> float:
    """Deterministic pseudo-random number in [0, 1) (no RNG state, same output every run)."""
    digest = hashlib.sha256(":".join(parts).encode()).digest()
    return int.from_bytes(digest[:8], "big") / 2**64


def stock_sql(org: str, lines: list[dict], catalog: dict) -> tuple[list[dict], list[str]]:
    """Demo stock: 8 weeks of usage around the weekly list amounts, plus one shelf count."""
    whole = {u["code"] for u in catalog["units"] if u["dimension"] == "count"}
    now = datetime.fromisoformat(catalog["meta"]["reference_now"])
    this_monday = now.date() - timedelta(days=now.isoweekday() - 1)
    counted_at = (now - timedelta(hours=15)).isoformat()  # the evening before

    def rnd(value: float, unit: str) -> str:
        return str(round(value)) if unit in whole else f"{value:.1f}"

    usage, counts, starting = [], [], []
    for i, line in enumerate(lines):
        product, unit, base = line["product_id"], line["unit"], float(line["quantity"])
        slope = -0.02 + 0.06 * unit_fraction(org, product, "trend")  # -2%..+4% a week
        for k in range(USAGE_WEEKS):
            week = this_monday - timedelta(weeks=USAGE_WEEKS - k)
            noise = 0.9 + 0.2 * unit_fraction(org, product, str(k))
            value = max(0.0, base * (1 + slope * (k - USAGE_WEEKS + 1)) * noise)
            usage.append(
                f"  ({q(org)}, {q(product)}, '{week.isoformat()}', {rnd(value, unit)}, {q(unit)}, "
                "'demo_estimate')"
            )
        on_hand = base * ON_HAND_WEEKS[i % len(ON_HAND_WEEKS)]
        counts.append(
            f"  ({q(org)}, {q(product)}, {rnd(on_hand, unit)}, {q(unit)}, '{counted_at}')"
        )
        starting.append(
            {"product_id": product, "quantity": rnd(on_hand, unit), "unit": unit,
             "counted_at": counted_at}
        )
    return starting, [
        "insert into public.stock_usage (org_id, product_id, week_start, quantity, unit, source) values\n"
        + ",\n".join(usage)
        + ";",
        "insert into public.stock_counts (org_id, product_id, quantity, unit, counted_at) values\n"
        + ",\n".join(counts)
        + ";",
    ]


def main() -> None:
    catalog = json.loads(CATALOG.read_text())
    out: list[str] = [
        "-- GENERATED by supabase/generate_seed_sql.py from data/seed/demo_catalog.json.",
        "-- Do not edit by hand. Fictional demo buyers only; local test password.",
        "",
    ]
    for buyer in catalog["buyers"]:
        org = buyer["id"]
        user_id = str(uuid.uuid5(NAMESPACE, org))
        email = demo_email(org)
        out += [
            f"-- {buyer['name']}",
            "insert into public.buyer_orgs (id, name, synthetic) values "
            f"({q(org)}, {q(buyer['name'])}, {str(buyer['synthetic']).lower()});",
            "insert into auth.users (instance_id, id, aud, role, email, encrypted_password,",
            "  email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at,",
            "  confirmation_token, email_change, email_change_token_new, recovery_token)",
            "values ('00000000-0000-0000-0000-000000000000', "
            f"{q(user_id)}, 'authenticated', 'authenticated', {q(email)},",
            f"  extensions.crypt({q(DEMO_PASSWORD)}, extensions.gen_salt('bf')), now(),",
            """  '{"provider":"email","providers":["email"]}', """
            f"""'{{"demo_org":"{org}"}}', now(), now(), '', '', '', '');""",
            "insert into auth.identities (id, user_id, provider_id, identity_data, provider,",
            "  last_sign_in_at, created_at, updated_at)",
            f"values ({q(user_id)}, {q(user_id)}, {q(user_id)},",
            f"""  '{{"sub":"{user_id}","email":"{email}","email_verified":true}}', 'email',""",
            "  now(), now(), now());",
            "insert into public.org_members (user_id, org_id, role) values "
            f"({q(user_id)}, {q(org)}, 'owner');",
        ]
        for lst in buyer["saved_lists"]:
            out.append(
                "insert into public.saved_lists (id, org_id, name) values "
                f"({q(lst['id'])}, {q(org)}, {q(lst['name'])});"
            )
            rows = [
                f"  ({q(lst['id'])}, {q(org)}, {q(line['product_id'])}, {line['quantity']}, "
                f"{q(line['unit'])}, {q(line['current_supplier_id'])}, {pos})"
                for pos, line in enumerate(lst["lines"])
            ]
            out.append(
                "insert into public.saved_list_lines "
                "(list_id, org_id, product_id, quantity, unit, current_supplier_id, position) values\n"
                + ",\n".join(rows)
                + ";"
            )
        # A brand-new buyer (no lists) starts with no stock at all.
        starting_counts, sql = (
            stock_sql(org, buyer["saved_lists"][0]["lines"], catalog) if buyer["saved_lists"] else ([], [])
        )
        out += sql
        # What "Reset demo" restores (supabase/migrations/20261113000000_demo_reset.sql).
        seed = {
            "lists": [
                {
                    "id": lst["id"],
                    "name": lst["name"],
                    "lines": [
                        {k: line[k] for k in ("product_id", "quantity", "unit", "current_supplier_id")}
                        for line in lst["lines"]
                    ],
                }
                for lst in buyer["saved_lists"]
            ],
            "counts": starting_counts,
        }
        out.append(
            "insert into public.demo_seed (org_id, data) values "
            f"({q(org)}, {q(json.dumps(seed, separators=(',', ':')))}::jsonb);"
        )
        out.append("")
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
